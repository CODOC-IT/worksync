CREATE TABLE work.Tasks
(
    TaskId                bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Tasks PRIMARY KEY,
    ProjectId             INT NOT NULL,
    ParentTaskId          BIGINT NULL,
    TaskNumber            INT NOT NULL,
    Title                 varchar(200) NOT NULL,
    Description           text NOT NULL,
    TaskStatusId          SMALLINT NOT NULL,
    PriorityId            SMALLINT NOT NULL,
    StartDate             DATE NOT NULL,
    DueDate               DATE NOT NULL,
    SortPosition          numeric(19,6) NOT NULL CONSTRAINT DF_Tasks_Position DEFAULT (0),
    CreatedByUserId       INT NOT NULL,
    DefaultReviewerUserId INT NULL,
    ActualStartedAtUtc    timestamptz(0) NULL,
    SubmittedAtUtc        timestamptz(0) NULL,
    CompletedAtUtc        timestamptz(0) NULL,
    CompletionSummary     varchar(2000) NULL,
    ArchivedAtUtc         timestamptz(0) NULL,
    ProjectArchivedAtUtc  timestamptz(0) NULL,
    CreatedAtUtc          timestamptz(0) NOT NULL CONSTRAINT DF_Tasks_Created DEFAULT (CURRENT_TIMESTAMP),
    UpdatedAtUtc          timestamptz(0) NOT NULL CONSTRAINT DF_Tasks_Updated DEFAULT (CURRENT_TIMESTAMP),
    RowVersion            bigint NOT NULL DEFAULT 1,
    CONSTRAINT UQ_Tasks_Project_Number UNIQUE (ProjectId, TaskNumber),
    CONSTRAINT CK_Tasks_Title CHECK (char_length(btrim(Title)) > 0),
    CONSTRAINT CK_Tasks_Description CHECK (char_length(btrim(Description)) > 0),
    CONSTRAINT CK_Tasks_Dates CHECK (DueDate >= StartDate),
    CONSTRAINT CK_Tasks_NoSelfParent CHECK (ParentTaskId IS NULL OR ParentTaskId <> TaskId),
    CONSTRAINT CK_Tasks_Completion CHECK
            ((CompletedAtUtc IS NULL AND CompletionSummary IS NULL) OR
             (CompletedAtUtc IS NOT NULL AND char_length(btrim(CompletionSummary)) > 0))
);

CREATE TABLE work.TaskAssignees
