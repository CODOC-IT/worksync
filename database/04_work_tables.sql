CREATE TABLE work.TaskChangeRequests
(
    ChangeRequestId       bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_TaskChangeRequests PRIMARY KEY,
    TaskId                BIGINT NOT NULL,
    ChangeRequestTypeId   SMALLINT NOT NULL,
    RequestedByUserId     INT NOT NULL,
    RequestReason         varchar(1000) NOT NULL,
    RequestStatus         VARCHAR(30) NOT NULL CONSTRAINT DF_ChangeRequests_Status DEFAULT ('Draft'),
    AssignedReviewerUserId INT NULL,
    SubmittedAtUtc        timestamptz(0) NULL,
    DecisionAtUtc         timestamptz(0) NULL,
    ExpiresAtUtc          timestamptz(0) NULL,
    CancelledAtUtc        timestamptz(0) NULL,
    CreatedAtUtc          timestamptz(0) NOT NULL CONSTRAINT DF_ChangeRequests_Created DEFAULT (CURRENT_TIMESTAMP),
    UpdatedAtUtc          timestamptz(0) NOT NULL CONSTRAINT DF_ChangeRequests_Updated DEFAULT (CURRENT_TIMESTAMP),
    RowVersion            bigint NOT NULL DEFAULT 1,
    CONSTRAINT CK_ChangeRequests_Reason CHECK (char_length(btrim(RequestReason)) > 0),
    CONSTRAINT CK_ChangeRequests_Status CHECK
            (RequestStatus IN ('Draft','Pending','ClarificationRequested','Approved','Rejected','Cancelled','Expired','Overridden')),
    CONSTRAINT CK_ChangeRequests_NoSelfReview CHECK
            (AssignedReviewerUserId IS NULL OR AssignedReviewerUserId <> RequestedByUserId),
    CONSTRAINT CK_ChangeRequests_Expiry CHECK (ExpiresAtUtc IS NULL OR SubmittedAtUtc IS NULL OR ExpiresAtUtc > SubmittedAtUtc)
);

CREATE TABLE work.TaskChangeRequestItems
(
    ChangeRequestItemId   bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_TaskChangeRequestItems PRIMARY KEY,
    ChangeRequestId       BIGINT NOT NULL,
    FieldCode             VARCHAR(50) NOT NULL,
    OldValueJson          text NULL,
    ProposedValueJson     text NULL,
    CONSTRAINT UQ_ChangeRequestItems_Field UNIQUE (ChangeRequestId, FieldCode),
    CONSTRAINT CK_ChangeRequestItems_Field CHECK (char_length(btrim(FieldCode)) > 0),
    CONSTRAINT CK_ChangeRequestItems_OldJson CHECK (OldValueJson IS NULL OR config.is_valid_json(OldValueJson)),
    CONSTRAINT CK_ChangeRequestItems_NewJson CHECK (ProposedValueJson IS NULL OR config.is_valid_json(ProposedValueJson)),
    CONSTRAINT CK_ChangeRequestItems_Different CHECK
            (COALESCE(OldValueJson, 'null') <> COALESCE(ProposedValueJson, 'null'))
);

CREATE TABLE work.ChangeRequestReviews
(
    ChangeRequestReviewId bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_ChangeRequestReviews PRIMARY KEY,
    ChangeRequestId       BIGINT NOT NULL,
    ReviewerUserId        INT NOT NULL,
    ReviewAction          VARCHAR(30) NOT NULL,
    ReviewNote            varchar(2000) NULL,
    ReviewerRoleCode      VARCHAR(40) NOT NULL,
    ReviewedAtUtc         timestamptz(0) NOT NULL CONSTRAINT DF_ChangeRequestReviews_Reviewed DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT CK_ChangeRequestReviews_Action CHECK
            (ReviewAction IN ('ClarificationRequested','Approved','Rejected','Overridden')),
    CONSTRAINT CK_ChangeRequestReviews_OverrideNote CHECK
            (ReviewAction <> 'Overridden' OR char_length(btrim(ReviewNote)) > 0)
);
