CREATE TABLE work.Projects
(
    ProjectId            int GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Projects PRIMARY KEY,
    OrganizationId       INT NOT NULL,
    DepartmentId         INT NULL,
    ProjectCode          varchar(30) NOT NULL,
    ProjectName          varchar(150) NOT NULL,
    Description          varchar(2000) NOT NULL,
    OwnerUserId          INT NOT NULL,
    ProjectStatusId      SMALLINT NOT NULL,
    PriorityId           SMALLINT NOT NULL,
    StartDate            DATE NOT NULL,
    EndDate              DATE NOT NULL,
    CreatedByUserId      INT NOT NULL,
    CreationReason       varchar(1000) NULL,
    ActivatedAtUtc       timestamptz(0) NULL,
    ArchivedAtUtc        timestamptz(0) NULL,
    ArchivedByUserId     INT NULL,
    ArchiveReason        varchar(500) NULL,
    CreatedAtUtc         timestamptz(0) NOT NULL CONSTRAINT DF_Projects_Created DEFAULT (CURRENT_TIMESTAMP),
    UpdatedAtUtc         timestamptz(0) NOT NULL CONSTRAINT DF_Projects_Updated DEFAULT (CURRENT_TIMESTAMP),
    RowVersion           bigint NOT NULL DEFAULT 1,
    CONSTRAINT UQ_Projects_Organization_Code UNIQUE (OrganizationId, ProjectCode),
    CONSTRAINT CK_Projects_Name CHECK (char_length(btrim(ProjectName)) > 0),
    CONSTRAINT CK_Projects_Description CHECK (char_length(btrim(Description)) > 0),
    CONSTRAINT CK_Projects_Dates CHECK (EndDate >= StartDate),
    CONSTRAINT CK_Projects_Archive CHECK
            ((ArchivedAtUtc IS NULL AND ArchivedByUserId IS NULL) OR
             (ArchivedAtUtc IS NOT NULL AND ArchivedByUserId IS NOT NULL AND char_length(btrim(ArchiveReason)) > 0))
);

CREATE TABLE work.ProjectMembers
(
    ProjectMemberId      bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_ProjectMembers PRIMARY KEY,
    ProjectId            INT NOT NULL,
    UserId               INT NOT NULL,
    MemberRoleCode       VARCHAR(30) NOT NULL CONSTRAINT DF_ProjectMembers_Role DEFAULT ('Member'),
    AddedByUserId        INT NOT NULL,
    JoinedAtUtc          timestamptz(0) NOT NULL CONSTRAINT DF_ProjectMembers_Joined DEFAULT (CURRENT_TIMESTAMP),
    LeftAtUtc            timestamptz(0) NULL,
    RemovedByUserId      INT NULL,
    RemovalReason        varchar(500) NULL,
    CONSTRAINT CK_ProjectMembers_Role CHECK (MemberRoleCode IN ('Owner','TeamLead','Member','Reviewer','Observer')),
    CONSTRAINT CK_ProjectMembers_Left CHECK
            ((LeftAtUtc IS NULL AND RemovedByUserId IS NULL) OR
             (LeftAtUtc IS NOT NULL AND RemovedByUserId IS NOT NULL AND LeftAtUtc >= JoinedAtUtc))
);

