-- Tables owned by the work schema.
-- Foreign keys are added after all 70 tables exist.

CREATE TABLE work.ProjectStatuses
(
    ProjectStatusId      smallint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_ProjectStatuses PRIMARY KEY,
    StatusCode           VARCHAR(30) NOT NULL CONSTRAINT UQ_ProjectStatuses_Code UNIQUE,
    StatusName           varchar(80) NOT NULL,
    SortOrder            SMALLINT NOT NULL,
    IsActiveState        boolean NOT NULL,
    IsTerminalState      boolean NOT NULL CONSTRAINT DF_ProjectStatuses_Terminal DEFAULT FALSE,
    CONSTRAINT UQ_ProjectStatuses_Order UNIQUE (SortOrder),
    CONSTRAINT CK_ProjectStatuses_Order CHECK (SortOrder >= 0)
);

CREATE TABLE work.TaskStatuses
