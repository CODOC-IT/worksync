    ADD CONSTRAINT FK_TeamMembers_Team FOREIGN KEY (TeamId)
        REFERENCES work.ProjectTeams(TeamId) ON DELETE CASCADE;

ALTER TABLE work.TeamMembers
    ADD CONSTRAINT FK_TeamMembers_Project FOREIGN KEY (ProjectId)
        REFERENCES work.Projects(ProjectId) ON DELETE CASCADE;

ALTER TABLE work.TeamMembers
    ADD CONSTRAINT FK_TeamMembers_User FOREIGN KEY (UserId)
        REFERENCES iam.Users(UserId);

ALTER TABLE work.Tasks
    ADD CONSTRAINT FK_Tasks_Team FOREIGN KEY (TeamId)
        REFERENCES work.ProjectTeams(TeamId) ON DELETE SET NULL;

ALTER TABLE work.SubtaskTransferRequests
    ADD CONSTRAINT FK_SubtaskTransferRequests_Subtask FOREIGN KEY (SubtaskId)
        REFERENCES work.Tasks(TaskId) ON DELETE CASCADE;

ALTER TABLE work.SubtaskTransferRequests
    ADD CONSTRAINT FK_SubtaskTransferRequests_Project FOREIGN KEY (ProjectId)
        REFERENCES work.Projects(ProjectId) ON DELETE CASCADE;

ALTER TABLE work.SubtaskTransferRequests
    ADD CONSTRAINT FK_SubtaskTransferRequests_FromTeam FOREIGN KEY (FromTeamId)
        REFERENCES work.ProjectTeams(TeamId) ON DELETE SET NULL;

ALTER TABLE work.SubtaskTransferRequests
    ADD CONSTRAINT FK_SubtaskTransferRequests_ToTeam FOREIGN KEY (ToTeamId)
        REFERENCES work.ProjectTeams(TeamId);

