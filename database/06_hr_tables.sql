CREATE TABLE hr.LeaveRequests
(
    LeaveRequestId        bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_LeaveRequests PRIMARY KEY,
    UserId                INT NOT NULL,
    LeaveTypeId           SMALLINT NOT NULL,
    StartDate             DATE NOT NULL,
    EndDate               DATE NOT NULL,
    IsPartialDay          boolean NOT NULL CONSTRAINT DF_LeaveRequests_Partial DEFAULT FALSE,
    PartialStartTime      TIME(0) NULL,
    PartialEndTime        TIME(0) NULL,
    Reason                varchar(1000) NOT NULL,
    RequestStatus         VARCHAR(30) NOT NULL CONSTRAINT DF_LeaveRequests_Status DEFAULT ('Pending'),
    AssignedReviewerUserId INT NULL,
    SubmittedAtUtc        timestamptz(0) NOT NULL CONSTRAINT DF_LeaveRequests_Submitted DEFAULT (CURRENT_TIMESTAMP),
    DecisionAtUtc         timestamptz(0) NULL,
    CancelledAtUtc        timestamptz(0) NULL,
    RowVersion            bigint NOT NULL DEFAULT 1,
    CONSTRAINT CK_LeaveRequests_Dates CHECK (EndDate >= StartDate),
    CONSTRAINT CK_LeaveRequests_Reason CHECK (char_length(btrim(Reason)) > 0),
    CONSTRAINT CK_LeaveRequests_Status CHECK
            (RequestStatus IN ('Pending','ClarificationRequested','Approved','Rejected','Cancelled','Escalated')),
    CONSTRAINT CK_LeaveRequests_NoSelfReview CHECK
            (AssignedReviewerUserId IS NULL OR AssignedReviewerUserId <> UserId),
    CONSTRAINT CK_LeaveRequests_Partial CHECK
            ((IsPartialDay IS FALSE AND PartialStartTime IS NULL AND PartialEndTime IS NULL) OR
             (IsPartialDay IS TRUE AND StartDate = EndDate AND PartialStartTime IS NOT NULL
              AND PartialEndTime IS NOT NULL AND PartialEndTime > PartialStartTime))
);

CREATE TABLE hr.LeaveRequestReviews
(
    LeaveRequestReviewId  bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_LeaveRequestReviews PRIMARY KEY,
    LeaveRequestId        BIGINT NOT NULL,
    ReviewerUserId        INT NOT NULL,
    DecisionCode          VARCHAR(30) NOT NULL,
    DecisionNote          varchar(2000) NULL,
    ReviewedAtUtc         timestamptz(0) NOT NULL CONSTRAINT DF_LeaveReviews_Reviewed DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT CK_LeaveReviews_Decision CHECK
            (DecisionCode IN ('ClarificationRequested','Approved','Rejected','Escalated','Overridden'))
);
