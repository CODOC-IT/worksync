let db: ReturnType<typeof newDb>;

before(() => {
  db = newDb({ autoCreateForeignKeyIndices: true });
  db.public.none(SCHEMA_DDL);
  db.public.none(SEED_DML);
  const { Pool } = db.adapters.createPg();
  setPoolForTesting(new Pool());
});

after(() => {
  resetPoolForTesting();
});

// Each test starts from a clean slate: wipe every notification/preference row written by the
// previous test, but leave the reference data (users/projects/tasks/notification types) alone.
// (An earlier version of this used db.backup()/.restore(), but that snapshot is taken against the
// raw IMemoryDb while all queries run through a pg Pool created once in before() — restoring left
// that Pool's live query path out of sync with the restored snapshot, so rows kept accumulating
// across tests. Explicit deletes have no such indirection.)
beforeEach(() => {
  db.public.none(`
    DELETE FROM notify.UserNotifications;
    DELETE FROM notify.Notifications;
    DELETE FROM notify.UserNotificationPreferences;
  `);
});

