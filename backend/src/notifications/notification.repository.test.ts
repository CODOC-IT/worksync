test('publishEvent: creates a Notification + fans out to all recipients', async () => {
  const service = await import('./notification.service.js');
  const created = await service.publishEvent({
    type: 'task_assigned',
    title: 'New Task Assigned',
    message: 'Admin User assigned you "Test Task" in Test Project.',
    recipientIds: ['usr-2', 'usr-3'],
    actorId: 'usr-1',
    projectId: 'prj-1',
    taskId: 'tsk-1'
  });

  assert.equal(created.length, 2);
  assert.deepEqual(created.map((n) => n.userId).sort(), ['usr-2', 'usr-3']);
  assert.equal(created[0].type, 'task_assigned');
  assert.equal(created[0].priority, 'High');
  assert.equal(created[0].read, false);
});

test('getNotificationsForUser: recipient sees their own notification, not others\'', async () => {
  const service = await import('./notification.service.js');
  await service.publishEvent({
    type: 'task_assigned',
    title: 'New Task Assigned',
    message: 'Assigned to usr-2.',
    recipientIds: ['usr-2'],
    actorId: 'usr-1'
  });

  const forRecipient = await service.getNotificationsForUser('usr-2');
  assert.equal(forRecipient.items.length, 1);
  assert.equal(forRecipient.items[0].userId, 'usr-2');
  assert.equal(forRecipient.items[0].actorId, 'usr-1');

  const forUnrelatedUser = await service.getNotificationsForUser('usr-3');
  assert.equal(forUnrelatedUser.items.length, 0);
});

test('markNotificationRead: read state is tracked independently per recipient', async () => {
  const service = await import('./notification.service.js');
  // Both usr-2 and usr-3 are recipients of the SAME broadcast event, so per the schema
  // (notify.Notifications is 1:N to notify.UserNotifications) they legitimately share one
  // NotificationId — each recipient's read state lives on their own UserNotifications row.
  const created = await service.publishEvent({
    type: 'task_assigned',
    title: 'New Task Assigned',
    message: 'Assigned.',
    recipientIds: ['usr-2', 'usr-3']
  });
  const notificationId = created[0].id;
  assert.equal(created[1].id, notificationId, 'both recipients should share one NotificationId');

  const usr3Result = await service.markNotificationRead('usr-3', notificationId);
  assert.equal(usr3Result, true, 'usr-3 owns a copy of this shared notification and can mark it read');

  const { items: usr3Items } = await service.getNotificationsForUser('usr-3');
  assert.equal(usr3Items[0].read, true);

  const { items: usr2Items } = await service.getNotificationsForUser('usr-2');
  assert.equal(usr2Items[0].read, false, 'usr-2\'s own copy must be unaffected by usr-3 marking theirs read');

  // usr-1 (the actor) has no UserNotifications row at all for this id — ownership is enforced by
  // the UPDATE...WHERE clause itself (FR-24), so this must be rejected rather than silently no-op.
  const unrelatedResult = await service.markNotificationRead('usr-1', notificationId);
  assert.equal(unrelatedResult, false, 'a non-recipient has no row to update and cannot mark it read');
});

test('markAllNotificationsRead: only affects the calling user\'s own notifications', async () => {
  const service = await import('./notification.service.js');
  await service.publishEvent({
    type: 'task_assigned',
    title: 'A',
    message: 'A',
    recipientIds: ['usr-2', 'usr-3']
  });
  await service.publishEvent({
    type: 'task_assigned',
    title: 'B',
    message: 'B',
    recipientIds: ['usr-2']
  });

  const count = await service.markAllNotificationsRead('usr-2');
  assert.equal(count, 2);

  const { items: usr3Items } = await service.getNotificationsForUser('usr-3');
  assert.equal(usr3Items.every((n) => !n.read), true, 'usr-3\'s notifications must remain unread');
});

test('clearNotification: soft-deletes (excluded from future queries) without a hard DELETE', async () => {
  const service = await import('./notification.service.js');
  const created = await service.publishEvent({
    type: 'task_assigned',
    title: 'A',
    message: 'A',
    recipientIds: ['usr-2']
  });

  const cleared = await service.clearNotification('usr-2', created[0].id);
  assert.equal(cleared, true);

  const { items } = await service.getNotificationsForUser('usr-2');
  assert.equal(items.length, 0);
});

test('preferences: disabling "assignments" suppresses task_assigned in-app delivery', async () => {
  const service = await import('./notification.service.js');

  await service.updatePreferences('usr-2', { assignments: false });
  await service.publishEvent({
    type: 'task_assigned',
    title: 'Suppressed for usr-2',
    message: 'Should be suppressed for usr-2, delivered for usr-3.',
    recipientIds: ['usr-2', 'usr-3']
  });

  const { items: usr2Items } = await service.getNotificationsForUser('usr-2');
  assert.equal(usr2Items.length, 0, 'usr-2 disabled assignments — should not see it');

  const { items: usr3Items } = await service.getNotificationsForUser('usr-3');
  assert.equal(usr3Items.length, 1, 'usr-3 never changed preferences — should still see it');
});

test('preferences: master inApp=false suppresses every type, not just categorized ones', async () => {
  const service = await import('./notification.service.js');

  await service.updatePreferences('usr-2', { inApp: false });
  await service.publishEvent({
    type: 'system',
    title: 'System notice',
    message: 'Uncategorized type, still gated by the master switch.',
    recipientIds: ['usr-2']
  });

  const { items } = await service.getNotificationsForUser('usr-2');
  assert.equal(items.length, 0);
});

