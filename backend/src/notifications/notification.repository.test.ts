import assert from 'node:assert/strict';
import test, { before, after, beforeEach } from 'node:test';
import { newDb } from 'pg-mem';
import { setPoolForTesting, resetPoolForTesting } from '../db/pool.js';

// Repository/service tests run against pg-mem (an in-memory Postgres emulator) executing the
// REAL notify.* table/constraint shapes from database/10_notify_tables.sql and their FK targets
// from database/02_org_tables.sql / 03_iam_tables.sql / 04_work_tables.sql — trimmed to the
// columns these tests actually exercise (pg-mem doesn't support every Postgres feature the full
// 70-table schema uses, e.g. GENERATED ALWAYS AS IDENTITY nuances and the PL/pgSQL support
// functions from 01_support_functions.sql, so SERIAL/BIGSERIAL stand in for
// GENERATED BY DEFAULT AS IDENTITY here). This is a test-only fixture — the real server always
// runs against the actual database/*.sql files via `psql -f database/setup.sql`, never this.
//
// No live Postgres/Docker was available in this environment (see the DB testing approach
// agreed with the user before this branch started) — this is the closest verification possible
// without one: real SQL, real constraints, real repository code, just an in-memory engine.

const SCHEMA_DDL = `
  CREATE SCHEMA org;
  CREATE SCHEMA iam;
  CREATE SCHEMA work;
  CREATE SCHEMA hr;
  CREATE SCHEMA notify;

  CREATE TABLE org.Organizations (
    OrganizationId SERIAL PRIMARY KEY,
    OrganizationCode VARCHAR(30) NOT NULL
  );

  CREATE TABLE iam.Users (
    UserId SERIAL PRIMARY KEY,
    OrganizationId INT NOT NULL REFERENCES org.Organizations(OrganizationId),
    Email VARCHAR(254) NOT NULL,
    DisplayName VARCHAR(170) NOT NULL,
    AccountStatus VARCHAR(20) NOT NULL DEFAULT 'Active'
  );

  CREATE TABLE work.ProjectStatuses (
    ProjectStatusId SERIAL PRIMARY KEY,
    StatusCode VARCHAR(30) NOT NULL UNIQUE
  );

  CREATE TABLE work.TaskStatuses (
    TaskStatusId SERIAL PRIMARY KEY,
    StatusCode VARCHAR(30) NOT NULL UNIQUE
  );

  CREATE TABLE work.Priorities (
    PriorityId SERIAL PRIMARY KEY,
    PriorityCode VARCHAR(20) NOT NULL UNIQUE
  );

  CREATE TABLE work.Projects (
    ProjectId SERIAL PRIMARY KEY,
    OrganizationId INT NOT NULL REFERENCES org.Organizations(OrganizationId),
    ProjectCode VARCHAR(30) NOT NULL,
    ProjectName VARCHAR(150) NOT NULL,
    OwnerUserId INT NOT NULL REFERENCES iam.Users(UserId),
    ProjectStatusId SMALLINT NOT NULL REFERENCES work.ProjectStatuses(ProjectStatusId),
    PriorityId SMALLINT NOT NULL REFERENCES work.Priorities(PriorityId)
  );

  CREATE TABLE work.Tasks (
    TaskId BIGSERIAL PRIMARY KEY,
    ProjectId INT NOT NULL REFERENCES work.Projects(ProjectId),
    Title VARCHAR(200) NOT NULL,
    TaskStatusId SMALLINT NOT NULL REFERENCES work.TaskStatuses(TaskStatusId),
    PriorityId SMALLINT NOT NULL REFERENCES work.Priorities(PriorityId)
  );

  CREATE TABLE work.TaskChangeRequests (
    ChangeRequestId BIGSERIAL PRIMARY KEY
  );

  CREATE TABLE hr.AttendanceCorrectionRequests (
    AttendanceCorrectionId BIGSERIAL PRIMARY KEY
  );

  CREATE TABLE hr.LeaveRequests (
    LeaveRequestId BIGSERIAL PRIMARY KEY
  );

  CREATE TABLE notify.NotificationTypes (
    NotificationTypeId SERIAL PRIMARY KEY,
    -- Real schema (database/10_notify_tables.sql) has TypeCode UNIQUE. Deliberately omitted here:
    -- pg-mem mishandles "WHERE col = ANY($::text[])" joined via LEFT JOIN when col carries a
    -- UNIQUE constraint — it silently returns zero rows instead of the matching ones (verified
    -- with a minimal repro outside this suite; the same query against real Postgres, or against
    -- this column without UNIQUE, returns correctly). Test-only DDL simplification, not a
    -- production behavior change — getPreferencesForTypes' production query is unaffected.
    TypeCode VARCHAR(50) NOT NULL,
    CategoryCode VARCHAR(30) NOT NULL,
    DefaultPriority VARCHAR(10) NOT NULL,
    IsMandatory BOOLEAN NOT NULL DEFAULT FALSE,
    DefaultEnabled BOOLEAN NOT NULL DEFAULT TRUE
  );

  CREATE TABLE notify.UserNotificationPreferences (
    UserId INT NOT NULL REFERENCES iam.Users(UserId),
    NotificationTypeId SMALLINT NOT NULL REFERENCES notify.NotificationTypes(NotificationTypeId),
    InAppEnabled BOOLEAN NOT NULL DEFAULT TRUE,
    EmailEnabled BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (UserId, NotificationTypeId)
  );

  CREATE TABLE notify.Notifications (
    NotificationId BIGSERIAL PRIMARY KEY,
    NotificationTypeId SMALLINT NOT NULL REFERENCES notify.NotificationTypes(NotificationTypeId),
    ActorUserId INT NULL REFERENCES iam.Users(UserId),
    ProjectId INT NULL REFERENCES work.Projects(ProjectId),
    TaskId BIGINT NULL REFERENCES work.Tasks(TaskId),
    ChangeRequestId BIGINT NULL REFERENCES work.TaskChangeRequests(ChangeRequestId),
    AttendanceCorrectionId BIGINT NULL REFERENCES hr.AttendanceCorrectionRequests(AttendanceCorrectionId),
    LeaveRequestId BIGINT NULL REFERENCES hr.LeaveRequests(LeaveRequestId),
    Title VARCHAR(200) NOT NULL,
    SafePreviewText VARCHAR(500) NULL,
    PriorityCode VARCHAR(10) NOT NULL,
    CreatedAtUtc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE notify.UserNotifications (
    NotificationId BIGINT NOT NULL REFERENCES notify.Notifications(NotificationId),
    RecipientUserId INT NOT NULL REFERENCES iam.Users(UserId),
    DeliveryStatus VARCHAR(20) NOT NULL DEFAULT 'Pending',
    DeliveredAtUtc TIMESTAMPTZ NULL,
    ReadAtUtc TIMESTAMPTZ NULL,
    OpenedAtUtc TIMESTAMPTZ NULL,
    ClearedAtUtc TIMESTAMPTZ NULL,
    PRIMARY KEY (NotificationId, RecipientUserId)
  );
`;

